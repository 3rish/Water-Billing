    private void btnCompActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompActionPerformed
        
        String vBillMonth, vAccNo, vAccName, vAdd;
        double vCons1 = 0, vCons2 = 0, vCons3 = 0, vCons4 = 0,vAm1 = 0, vAm2 = 0, vAm3 = 0, vAm4 = 0, vTot = 0;
        double vRate1 = 52.67, vRate2 = 56.45, vRate3 = 62.38, vRate4 = 67.69;
        int vConsump = 0;
        String strCons1, strCons2, strCons3, strCons4, strAm1, strAm2, strAm3, strAm4, strTot;
        
        txtBillMonth.setEditable(false);
        txtAccNo.setEditable(false);
        txtAccName.setEditable(false);
        txtAdd.setEditable(false);
        txtConsump.setEditable(false);
        txtCons1.setEditable(false);
        txtCons2.setEditable(false);
        txtCons3.setEditable(false);
        txtCons4.setEditable(false);
        txtAm1.setEditable(false);
        txtAm2.setEditable(false);
        txtAm3.setEditable(false);
        txtAm4.setEditable(false);
        txtTot.setEditable(false);
        
        vBillMonth = txtBillMonth.getText();
        vAccNo = txtAccNo.getText();
        vAccName = txtAccName.getText();
        vAdd = txtAdd.getText();
        vConsump = Integer.parseInt(txtConsump.getText());
        
        double CMBcount = vConsump;
        
        if (CMBcount < 31) {
            do {
                if (CMBcount < 11) {
                    vCons1 = 10;
                    if (CMBcount < 10) {
                        break;
                    }
                    else {
                        CMBcount = CMBcount - 10;
                    }
                    break;
                }
                if (CMBcount < 21) {
                    vCons2 = 10;
                    CMBcount = CMBcount - 10;
                }
                if (CMBcount < 31) {
                    vCons3 = 10;
                    CMBcount = CMBcount - 10;
                }      
            } while (CMBcount != 0);
        }
        
        if (CMBcount > 30) {
            vCons1 = 10;
            CMBcount = CMBcount - 10;
            vCons2 = 10;
            CMBcount = CMBcount - 10;
            vCons3 = 10;
            CMBcount = CMBcount - 10;
            vCons4 = CMBcount;
        }
        
        strCons1 = String.format("%.2f", vCons1);
        txtCons1.setText(strCons1);
        
        strCons2 = String.format("%.2f", vCons2);
        txtCons2.setText(strCons2);
        
        strCons3 = String.format("%.2f", vCons3);
        txtCons3.setText(strCons3);
        
        strCons4 = String.format("%.2f", vCons4);
        txtCons4.setText(strCons4);
        
        vAm1 = vCons1 * vRate1;
        vAm2 = vCons2 * vRate2;
        vAm3 = vCons3 * vRate3;
        vAm4 = vCons4 * vRate4;
        
        strAm1 = String.format("%.2f", vAm1);
        txtAm1.setText(strAm1);
        
        strAm2 = String.format("%.2f", vAm2);
        txtAm2.setText(strAm2);
        
        strAm3 = String.format("%.2f", vAm3);
        txtAm3.setText(strAm3);
        
        strAm4 = String.format("%.2f", vAm4);
        txtAm4.setText(strAm4);
        
        vTot = vAm1 + vAm2 + vAm3 + vAm4;
        strTot = String.format("%.2f", vTot);
        txtTot.setText(strTot);
        
        cus = vBillMonth + "|" + vAccNo + "|" + vAccName + "|" + vAdd + "|" + vTot + "\n";
    }//GEN-LAST:event_btnCompActionPerformed

